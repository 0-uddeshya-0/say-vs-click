#!/usr/bin/env python3
"""Builds ../items.js from items.json (the item bank, source of truth).

Usage: python3 tools/build_items.py [items.json] [items.js]
Edit the bank on the admin page (Items tab), export it as items.json, replace tools/items.json and run this script.
"""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "items.json")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "items.js")
bank = json.load(open(src, encoding="utf-8"))
head = '''/*
 * Item bank, version %s.
 * 16 yes/no questions in four groups of four (two with the key "yes", two with the key "no").
 * Questions 1-6, 9-14 and 16 are adapted from StrategyQA (Geva et al. 2021), the question set used by
 * Sun et al. (2026a); wording was simplified. Questions 7, 8 and 15 were written for this study.
 * Source texts are study-written summaries of the named English Wikipedia articles (url); every number and
 * named fact in them was checked against the article text on 17 November 2026. The texts are identical in the
 * supported and the unsupported version of an item.
 *   key        correct answer to the question ("yes" / "no")
 *   answer.s   AI answer in the supported version (agrees with the key and the sources)
 *   answer.u   AI answer in the unsupported version (contradicts the key and the sources)
 *   trace.s/u  reasoning trace shown with the respective answer (trace condition only)
 *   sources    title, origin, text, url (the article the participant can open in a new tab)
 *   de         German version of question, answers, traces and sources (same content, same order)
 * Generated by tools/build_items.py from tools/items.json. Do not edit by hand.
 */
''' % bank["version"]
js = (head + "const ITEMS_VERSION = " + json.dumps("bundled-" + bank["version"]) + ";\nconst ITEMS = "
      + json.dumps(bank["items"], ensure_ascii=False, indent=1) + ";\nconst PRACTICE = "
      + json.dumps(bank["practice"], ensure_ascii=False, indent=1)
      + ";\n\nif (typeof module !== \"undefined\") module.exports = { ITEMS, PRACTICE, ITEMS_VERSION };\n")
open(dst, "w", encoding="utf-8").write(js)
print("items:", len(bank["items"]), "bytes:", len(js.encode("utf-8")), "version:", bank["version"])
